#!/usr/bin/env bash
# 写完自查：扫描 writing 规则里的常见问题。用法：bash check.sh <文件或目录>...
# 命中不等于必须改，按 SKILL.md 的口诀逐处判断。
set -u
[ $# -gt 0 ] || { echo "用法: $0 <文件或目录>..." >&2; exit 2; }

echo "== 1. 口径、大词与疑似生硬组合"
rg -n '口径|抓手|赋能|闭环|维度|层面|机制|体系|进行[^行中]|物理上|一侧' "$@"

echo "== 2. 门禁与契约（按 SKILL.md 的命中规则判断）"
rg -n '门禁|契约' "$@"

echo "== 3. 解释压过数据（逐处往回看一句有没有数字、代码或 Trace）"
rg -n '这说明|这表明|(测试|结果|数据|实验)表明|可以看出|由此可见|显而易见|显然|意味着|充分(证明|体现)' "$@"

echo "== 4. 空转过渡与套话"
rg -n '在.*方面|对于.*而言|就.*而言|综上所述|值得注意的是|深入探讨' "$@"

echo "== 5. 感叹号、emoji、夸张词与伪量化"
rg -n '[!！?？]{2,}|[\x{1F300}-\x{1FAFF}\x{2600}-\x{27BF}]|非常|极其|颠覆|碾压|秒杀|震惊|炸裂|爆表|重磅|天花板|神器|拉满|起飞|(企业|工业|军工|毫?秒)级' "$@"

echo "== 6. 常见专有名词大小写写错（不含 URL、路径和代码里的小写）"
rg -n -P '(?<![\w./-])(github|Github|postgresql|Postgresql|postgreSQL|nginx|NGINX|kubernetes|redis|REDIS|mysql|Mysql|MySql|MYSQL)(?![\w./-])' "$@"

exit 0
